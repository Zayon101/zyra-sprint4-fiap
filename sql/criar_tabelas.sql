-- Zyra | Sprint 4 | Etapa 2
-- Execute no usuário Oracle da equipe, nunca com SYS/SYSTEM.
-- Requer Oracle Database 12c ou superior para as colunas IDENTITY.
-- Não exclui nem modifica as tabelas: apenas cria as estruturas novas.

CREATE TABLE ZYRA_USUARIOS (
    ID NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME VARCHAR2(120 CHAR) NOT NULL,
    PONTOS NUMBER(12) DEFAULT 500 NOT NULL,
    CONSTRAINT PK_ZYRA_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT CK_ZYRA_USUARIOS_NOME CHECK (TRIM(NOME) IS NOT NULL AND LENGTH(TRIM(NOME)) >= 3),
    CONSTRAINT CK_ZYRA_USUARIOS_PONTOS CHECK (PONTOS >= 0)
);

CREATE TABLE ZYRA_TROCAS (
    ID NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USUARIO_ID NUMBER(10) NOT NULL,
    PASSAGEM VARCHAR2(80 CHAR) NOT NULL,
    VIAGENS NUMBER(8) NOT NULL,
    CUSTO_PONTOS NUMBER(12) NOT NULL,
    VALOR_REAIS NUMBER(12,2) NOT NULL,
    DATA_TROCA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ZYRA_TROCAS PRIMARY KEY (ID),
    CONSTRAINT FK_ZYRA_TROCAS_USUARIO
        FOREIGN KEY (USUARIO_ID) REFERENCES ZYRA_USUARIOS (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_ZYRA_TROCAS_VIAGENS CHECK (VIAGENS > 0),
    CONSTRAINT CK_ZYRA_TROCAS_CUSTO CHECK (CUSTO_PONTOS > 0),
    CONSTRAINT CK_ZYRA_TROCAS_VALOR CHECK (VALOR_REAIS >= 0)
);

CREATE INDEX IX_ZYRA_TROCAS_USUARIO ON ZYRA_TROCAS (USUARIO_ID);
